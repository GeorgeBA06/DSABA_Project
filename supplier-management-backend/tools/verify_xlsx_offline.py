"""Execute the actual dependency-free XLSX writer with javac and validate OOXML with openpyxl."""

from pathlib import Path
import subprocess, tempfile, zipfile, xml.etree.ElementTree as ET

src = (
    Path(__file__).resolve().parents[1]
    / "src/main/java/by/bsuir/supplier/service/query/SmallXlsxWriter.java"
)
with tempfile.TemporaryDirectory() as d:
    root = Path(d)
    pkg = root / "by/bsuir/supplier/service/query"
    pkg.mkdir(parents=True)
    (pkg / "SmallXlsxWriter.java").write_text(src.read_text())
    package_src = src.parents[2]  # .../by/bsuir/supplier
    for name in ("SupplierStatus", "RatingBand", "RatingState"):
        enum_src = package_src / "entity/enums" / f"{name}.java"
        target = root / "by/bsuir/supplier/entity/enums" / f"{name}.java"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(enum_src.read_text())
    report_src = package_src / "dto/response/SupplierReportRow.java"
    report_target = root / "by/bsuir/supplier/dto/response/SupplierReportRow.java"
    report_target.parent.mkdir(parents=True, exist_ok=True)
    report_target.write_text(report_src.read_text())
    (root / "XlsxRunner.java").write_text("""import by.bsuir.supplier.service.query.*;
import by.bsuir.supplier.dto.response.SupplierReportRow;
import by.bsuir.supplier.entity.enums.*;
import java.math.*;import java.util.*;import java.nio.file.*;
public class XlsxRunner {
 public static void main(String[] a) throws Exception {
   var rows=java.util.List.of(new SupplierReportRow(UUID.randomUUID(),"ООО <Тест> & Снабжение", SupplierStatus.ACTIVE,new BigDecimal("86.5"),RatingBand.HIGH,RatingState.PUBLISHED));
   Files.write(Path.of(a[0]),SmallXlsxWriter.supplierReport(rows));
 }
}
""")
    sources = list(root.rglob("*.java"))
    run = subprocess.run(
        [
            "javac",
            "--release",
            "21",
            "-d",
            str(root / "out"),
            *[str(f) for f in sources],
        ],
        capture_output=True,
        text=True,
    )
    if run.returncode:
        raise SystemExit(run.stderr)
    book = root / "report.xlsx"
    run = subprocess.run(
        ["java", "-cp", str(root / "out"), "XlsxRunner", str(book)],
        capture_output=True,
        text=True,
    )
    if run.returncode:
        raise SystemExit(run.stderr)
    with zipfile.ZipFile(book) as z:
        assert z.testzip() is None
        for entry in z.namelist():
            if entry.endswith(".xml") or entry.endswith(".rels"):
                ET.fromstring(z.read(entry))
        content = z.read("xl/worksheets/sheet1.xml").decode("utf-8")
        assert "ООО &lt;Тест&gt; &amp; Снабжение" in content, content
    try:
        from openpyxl import load_workbook

        wb = load_workbook(book, read_only=True, data_only=True)
        assert wb.active["B2"].value == "ООО <Тест> & Снабжение"
        assert wb.active["D2"].value == 86.5
        wb.close()
        print(
            "PASS: XLSX generated by Java, ZIP/XML valid, Excel cells read correctly by openpyxl"
        )
    except ImportError:
        print("PASS: XLSX generated by Java, ZIP/XML well-formed; openpyxl unavailable")
